typedef struct {
    uint64_t low;
    uint64_t high;
} PrimeMask;

typedef struct {
    _Atomic uint8_t *status;
    uint32_t *masks;
    PrimeMask *used_primes;
    uint64_t *values;
    size_t capacity;
    _Atomic size_t size;
    bool bounded;
    pthread_mutex_t *locks;
    size_t lock_count;
    _Atomic uint64_t victim_counter;
} ConcurrentMemo;

typedef struct {
    ConcurrentMemo memo;
    _Atomic uint64_t computed_states;
    _Atomic uint64_t nonzero_states;
    _Atomic uint64_t pruned_states;
    _Atomic uint64_t wait_count;
    unsigned thread_count;
    unsigned n;
    uint16_t low_sum[LOW_SIZE];
    uint16_t high_sum[HIGH_SIZE];
    PrimeMask prime_bit[MAX_SUM + 1U];
    PrimeMask relevant_primes[MAX_SUM + 1U];
    uint16_t next_prime[MAX_SUM + 2U];
    unsigned primes[128];
    unsigned prime_count;
} Context;

typedef struct {
    Context *context;
    uint32_t *mitm_grouped[MAX_N];
    size_t mitm_capacity[MAX_N];
} Worker;

typedef struct {
    size_t index;
    uint32_t mask;
    PrimeMask used_primes;
} MemoToken;

typedef struct {
    uint32_t block_rest;
    uint16_t block_sum;
} RootTask;

