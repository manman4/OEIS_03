/*
 * A322308 -- exact meet-in-the-middle evaluator.
 *
 * Count permutations sigma of {1,...,n} satisfying
 *
 *   |sigma(i+j)-sigma(i)| >= 5,
 *             1 <= j <= 4,  1 <= i <= n-j.
 *
 * This program differs from 322308_01.c at the whole-permutation level.
 * Program 01 propagates prefixes to length n; program 02 stops at the middle
 * and joins two independently counted half paths.  Both use the necessary
 * width-four local state, but their completion algorithms are different.
 *
 * Let P_k(S,a,b,c,d) count valid orderings of S ending a,b,c,d. Split a full
 * permutation as (...,a,b,c,d | e,f,g,h,...). Reversing the right half gives
 * R(e,f,g,h)=P_r(T,h,g,f,e). Exactly ten inequalities cross the split:
 *
 *   d~e,d~f,d~g,d~h, c~e,c~f,c~g, b~e,b~f, a~e,
 *                                         where x~y means |x-y|>=5.
 *
 * Each half table is expanded from complement-orbit representatives into
 * exact endpoint records and sorted by its used-value mask.  Only an
 * actually present left mask S and its actually present complementary right
 * mask T are joined, and only endpoint quadruples stored in those groups are
 * tested against the ten inequalities.  This sparse grouped join avoids the
 * enormous n^8 Cartesian endpoint space.
 * For even n, S and T give reversal-paired full permutations, so only
 * S<T is joined and the result is doubled.
 *
 * Half paths are generated by sparse subset DP, but only through length
 * ceil(n/2).  Two hash layers are used.  Before a growing layer is filled,
 * its obsolete buffer is released and a damped estimate from the preceding
 * layer sizes is reserved; unlike incremental growth, this normally avoids
 * holding old and new large buffers simultaneously.
 *
 * Value complementation v -> n-1-v is also used.  A hash slot stores the
 * combined count of the two reflected states. Every ordered-quadruple state
 * has orbit size two, so lookup divides the stored value by two to recover
 * P_k(S,a,b,c,d). --no-symmetry disables this optimization; --check compares
 * the two versions on small n.
 *
 * Safety:
 *   - half-path counts and the final positive sum are bounded by n!;
 *   - 34! < 2^128, so unsigned 128-bit arithmetic is exact for n<=34;
 *   - additions, subtractions, products, key packing, table growth, and
 *     allocation sizes are checked anyway;
 *   - a main state slot is 16 bytes (key + low count word); nonzero high
 *     words alone occupy a separate sparse table, preserving exact 128-bit
 *     coefficients without paying 24 bytes for every hash slot;
 *   - --memory-mib is a hard budget for DP tables and endpoint records;
 *   - a range run flushes b322308_02_part.txt after each completed term
 *     and renames it atomically to b322308_02.txt only after success.
 *
 * The integer type is safe through n=34, but the exponential half-state
 * table normally sets a much smaller practical limit.
 *
 * Build:
 *
 *   clang -O3 -std=c11 -Wall -Wextra -Wpedantic \
 *     322308_02.c -o 322308_02
 *
 * Usage:
 *
 *   ./322308_02
 *   ./322308_02 --term 28 --memory-mib 2048
 *   ./322308_02 --upto 28 --memory-mib 2048
 *   ./322308_02 --no-symmetry --term 20
 *   ./322308_02 --check
 *
 * Reference:
 *   https://oeis.org/A322308
 */

